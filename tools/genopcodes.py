#!/usr/bin/env python3
"""Generates internal/pickle/opcodes.go from a CPython Lib/pickletools.py.

The pickle opcode table is the single fact every other pickle behaviour in sc4n
derives from, so it is transcribed mechanically rather than by hand: a
typo in an argument width or an endianness would be invisible in review and
catastrophic at runtime (a wrong BINFLOAT width alone would mis-decode every
FLOAT opcode in every stream).

usage:
    python3 tools/genopcodes.py /usr/lib/python3.14/pickletools.py > internal/pickle/opcodes.go

The `opcodes = [ ... ]` list is read from the file's own text (not by importing
it) so that the generator works against any checkout of any CPython version, and
the emitted header records the line range and the file's sha256 so a reviewer can
diff the transcription against that exact revision.
"""

import hashlib
import re
import sys

# argKind order in the Go enum. Emitting an explicit order keeps the generated
# file diffable: adding an argument kind changes one line, not every row.
ARG_KINDS = [
    "none",
    "uint1",
    "uint2",
    "uint4",
    "int4",
    "uint8",
    "float8",
    "decimalnl_short",
    "decimalnl_long",
    "floatnl",
    "stringnl",
    "stringnl_noescape",
    "stringnl_noescape_pair",
    "unicodestringnl",
    "string1",
    "string4",
    "bytes1",
    "bytes4",
    "bytes8",
    "bytearray8",
    "unicodestring1",
    "unicodestring4",
    "unicodestring8",
    "long1",
    "long4",
]

ENTRY = re.compile(
    r"I\(name=(?P<nameq>['\"])(?P<name>[A-Z0-9_]+)(?P=nameq),\s*"
    r"code=(?P<code>'[^']*'|\"[^\"]*\"),\s*"
    r"arg=(?P<arg>\w+|None),\s*"
    r"stack_before=\[(?P<before>.*?)\],\s*"
    r"stack_after=\[(?P<after>.*?)\],\s*"
    r"(?:proto=(?P<proto>\d+),\s*)?",
    re.S,
)


def fail(message):
    """Exit non-zero even under python -O, where assert would disappear."""
    print("genopcodes: " + message, file=sys.stderr)
    sys.exit(1)


def parse(path):
    text = open(path, encoding="utf-8").read()
    start = text.index("opcodes = [")
    # The list ends at the first line that is exactly "]" after the start, which
    # is how pickletools.py closes it before "del I".
    end = text.index("\ndel I", start)
    body = text[start:end]
    entries = []
    for m in ENTRY.finditer(body):
        code = m.group("code")[1:-1]
        code = code.encode("utf-8").decode("unicode_escape").encode("latin-1")
        if len(code) != 1:
            fail("opcode %s has code length %d, want 1" % (m.group("name"), len(code)))
        arg = m.group("arg")
        if arg == "None":
            kind = "argNone"
        else:
            if arg not in ARG_KINDS:
                fail("unknown argument kind %r for %s" % (arg, m.group("name")))
            kind = "arg" + "".join(p.capitalize() for p in arg.split("_"))
        before = [x for x in re.split(r",\s*", m.group("before").strip()) if x]
        after = [x for x in re.split(r",\s*", m.group("after").strip()) if x]
        entries.append(
            {
                "name": m.group("name"),
                "code": code[0],
                "arg": kind,
                "pops": len(before),
                "pushes": len(after),
                "proto": int(m.group("proto") or 0),
            }
        )
    # A project line number is the offset of the "opcodes = [" line.
    lines = text[:start].count("\n") + 1
    return entries, lines, text[:end].count("\n") + 1 - lines + 1, hashlib.sha256(text.encode()).hexdigest()


def main():
    path = sys.argv[1]
    entries, start_line, count, digest = parse(path)
    by_code = {}
    for e in entries:
        if e["code"] in by_code:
            fail("duplicate code %r" % (e["code"],))
        by_code[e["code"]] = e
    if len(entries) != 68:
        fail("parsed %d entries, want 68" % len(entries))

    out = []
    w = out.append
    w("// Code generated by tools/genopcodes.py. DO NOT EDIT.")
    w("//")
    w("// Source: CPython Lib/pickletools.py")
    w(f"//   file    {path}")
    w(f"//   sha256  {digest}")
    w(f"//   table   lines {start_line}-{start_line + count - 1} (the `opcodes = [ ... ]` list)")
    w("//")
    w("// The list's own uniqueness checks (pickletools.py, immediately after the list) guarantee one")
    w("// entry per name and per code, and the generator exits on the same violation, so the table below is a")
    w("// total function over all 256 byte values once OP_UNKNOWN fills the gaps.")
    w("package pickle")
    w("")
    w("// argKind is the wire encoding of an opcode's argument, transcribed from the")
    w("// ArgumentDescriptor each opcode names.")
    w("type argKind uint8")
    w("")
    w("const (")
    for i, k in enumerate(ARG_KINDS):
        go = "arg" + "".join(p.capitalize() for p in k.split("_"))
        if k == "none":
            go = "argNone"
        # The first constant is the zero value so an unfilled table entry is
        # unambiguous.
        if i == 0:
            w(f"\t{go} argKind = iota")
        else:
            w(f"\t{go}")
    w(")")
    w("")
    w("// opcodeInfo describes one opcode. pops and pushes are pickletools' own stack")
    w("// annotations: they describe the opcode's ordinary effect and are 0 for the")
    w("// stack-shuffling opcodes (MARK, POP_MARK, MEMOIZE, the GET family) whose real")
    w("// effect the walker implements explicitly. They are metadata, never the")
    w("// behaviour of record.")
    w("type opcodeInfo struct {")
    w("\tname   string")
    w("\targ    argKind")
    w("\tpops   int8")
    w("\tpushes int8")
    w("\tproto  byte")
    w("}")
    w("")
    w("// opTable is indexed by the opcode byte. Bytes with no entry are OP_UNKNOWN.")
    w("var opTable = [256]opcodeInfo{")
    for code in range(256):
        e = by_code.get(code)
        if e is None:
            continue
        w(
            '\t0x%02x: {name: "%s", arg: %s, pops: %d, pushes: %d, proto: %d},'
            % (code, e["name"], e["arg"], e["pops"], e["pushes"], e["proto"])
        )
    w("}")
    w("")
    w("// highestProtocol is CPython's pickle.HIGHEST_PROTOCOL, the largest protocol")
    w("// number any opcode in the table declares. A stream that opens with a PROTO")
    w("// byte above it is reported rather than decoded.")
    highest = max(e["proto"] for e in entries)
    w(f"const highestProtocol = {highest}")
    w("")
    w("// opUnknownName is the name reported for a byte with no entry.")
    w('const opUnknownName = "OP_UNKNOWN"')
    w("")
    w("func opcodeName(code byte) string {")
    w("\tif n := opTable[code].name; n != \"\" {")
    w("\t\treturn n")
    w("\t}")
    w("\treturn opUnknownName")
    w("}")
    w("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
