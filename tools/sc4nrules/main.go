// bucket is one section of docs/triage.md. Every rule's prefix maps to exactly
// one, so the catalogue entry can point at the decision procedure for its class.
type bucket struct {
	Anchor string
	Title  string
	// Rule prefixes that belong here, matched longest-first so a more specific
	// prefix wins over a shorter one.
	Prefixes []string
}

