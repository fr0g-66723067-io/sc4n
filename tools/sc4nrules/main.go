// bucketFor returns the bucket a rule belongs to, longest prefix first, so
// SC4N-ARCHIVE-TRUNCATED and SC4N-PATH-ESCAPE can never be attributed by a
// shorter match.
func bucketFor(id string) (bucket, bool) {
	best, found := bucket{}, false
	bestLen := 0
	for _, b := range buckets {
		for _, p := range b.Prefixes {
			if strings.HasPrefix(id, p) && len(p) > bestLen {
				best, found, bestLen = b, true, len(p)
			}
		}
	}
	return best, found
}

func main() {
	out := flag.String("out", "docs/rules.md", "file to write (- for stdout)")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "sc4nrules takes no positional arguments")
		os.Exit(2)
	}
	doc, err := render(report.Rules())
	if err != nil {
		fmt.Fprintf(os.Stderr, "sc4nrules: %v\n", err)
		os.Exit(1)
	}
	if *out == "-" {
		os.Stdout.Write(doc)
		return
	}
	if err := os.WriteFile(*out, doc, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "sc4nrules: %v\n", err)
		os.Exit(1)
	}
}

// render builds the document. It is deterministic: the registry is sorted by ID,
// the bucket table is fixed, and nothing host- or time-dependent is written.
func render(rules []*report.Rule) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprint(&b, "<!-- Generated by `make rules-doc` from internal/report. Do not edit. -->\n\n")
	fmt.Fprint(&b, "# Rule catalogue\n\n")
	fmt.Fprintf(&b, "Every rule sc4n can emit, generated from the rule registry: %d rules, %d of\n", len(rules), cweCount(rules))
	fmt.Fprint(&b, "them naming a CWE. `sc4n rules` prints the same table with the rationale for\n")
	fmt.Fprint(&b, "each rule; this page exists so a reader holding a finding can look it up\n")
	fmt.Fprint(&b, "without a binary, and so every rule carries a link to what to do with it.\n\n")
	fmt.Fprint(&b, "Severity is what happens if the finding is real, confidence is how sure the\n")
	fmt.Fprint(&b, "detector is; `docs/triage.md` explains how the two combine into a decision.\n\n")

	fmt.Fprint(&b, "## Index\n\n")
	fmt.Fprint(&b, "| rule | severity | confidence | CWE | title |\n|---|---|---|---|---|\n")
	for _, r := range rules {
		fmt.Fprintf(&b, "| [`%s`](#%s) | %s | %s | %s | %s |\n",
			r.ID, strings.ToLower(r.ID), r.Severity, r.Confidence, cweCell(r), cell(r.Title))
	}
	fmt.Fprintf(&b, "\n%d rule(s).\n\n", len(rules))

	// Group by bucket so the detail sections follow the triage order rather than
	// the ID order: a reader who lands on one rule sees its neighbours.
	for _, bk := range buckets {
		var group []*report.Rule
		for _, r := range rules {
			if got, ok := bucketFor(r.ID); ok && got.Anchor == bk.Anchor {
				group = append(group, r)
			}
		}
		if len(group) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n", bk.Title)
		fmt.Fprintf(&b, "How to act on these: [`docs/triage.md#%s`](../triage.md#%s).\n", bk.Anchor, bk.Anchor)
		for _, r := range group {
			fmt.Fprintf(&b, "\n### %s\n\n", r.ID)
			fmt.Fprintf(&b, "**%s** · severity `%s` · confidence `%s` · class `%s`",
				cell(r.Title), r.Severity, r.Confidence, r.Class)
			if len(r.CWE) > 0 {
				fmt.Fprintf(&b, " · %s", strings.Join(linkCWEs(r.CWE), ", "))
			}
			fmt.Fprint(&b, "\n\n")
			fmt.Fprint(&b, strings.TrimSpace(r.Description))
			fmt.Fprint(&b, "\n\n")
			if len(r.Refs) > 0 {
				fmt.Fprint(&b, "References:\n\n")
				for _, ref := range r.Refs {
					fmt.Fprintf(&b, "- %s\n", ref)
				}
				fmt.Fprint(&b, "\n")
			}
		}
	}
	return b.Bytes(), nil
}

func cweCount(rules []*report.Rule) int {
	n := 0
	for _, r := range rules {
		if len(r.CWE) > 0 {
			n++
		}
	}
	return n
}

func cweCell(r *report.Rule) string {
	if len(r.CWE) == 0 {
		return "-"
	}
	return strings.Join(r.CWE, " ")
}

// linkCWEs turns CWE-502 into a link to the MITRE page, because the CWE name is
// the one piece of the finding a reader may want to read up on.
func linkCWEs(cwes []string) []string {
	out := make([]string, 0, len(cwes))
	for _, c := range cwes {
		num := strings.TrimPrefix(c, "CWE-")
		out = append(out, fmt.Sprintf("[%s](https://cwe.mitre.org/data/definitions/%s.html)", c, num))
	}
	return out
}

// cell keeps a title from breaking a table: titles are authored, not input, so a
// pipe is the only character that can.
func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

