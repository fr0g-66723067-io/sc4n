// Command sc4nrules writes docs/rules.md from the live rule registry.
//
// The catalogue is generated for one reason: a hand-maintained list of 205 rules
// is stale the moment a detector lands, and the first thing a reader does after
// seeing a finding is look the rule up. The generator is also the only place that
// can enforce the triage contract — every rule maps to a bucket in
// docs/triage.md, and a rule with no bucket fails the build instead of shipping
// with no "what now" for the person holding the finding.
//
// `make rules-doc` writes the file; `go test ./tools/sc4nrules` fails when the
// committed file and the registry disagree, so a rule added without regenerating
// is caught in CI rather than read as current by a user.
